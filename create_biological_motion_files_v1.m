function create_biological_motion_files_v1()

writeFile('make_bm_stimulus_table.m', make_stimulus_table_code());
writeFile('make_bm_trial_order.m', make_trial_order_code());
writeFile('run_biological_motion_individual.m', run_individual_code());
writeFile('bm_play_video_trial.m', play_video_code());
writeFile('bm_get_response.m', response_code());
writeFile('bm_save_row.m', save_row_code());
writeFile('bm_compute_sdt.m', compute_sdt_code());
writeFile('bm_convert_stimuli_to_mp4.m', convert_code());

if ~exist('stimuli', 'dir'); mkdir('stimuli'); end
if ~exist('data', 'dir'); mkdir('data'); end

disp('Created biological motion task files.');
disp('If AVI files give codec errors, run: bm_convert_stimuli_to_mp4');
disp('Then run: make_bm_stimulus_table');
disp('Then run: make_bm_trial_order');
end

function writeFile(fname, txt)
fid = fopen(fname, 'w');
if fid < 0
    error('Could not create %s', fname);
end
fprintf(fid, '%s', txt);
fclose(fid);
end

function txt = make_stimulus_table_code()
txt = [
"function stimTable = make_bm_stimulus_table(stimDir)" newline ...
"% Creates stimuli.csv by parsing video filenames." newline ...
"% Uses stimuli_mp4 if available; otherwise uses stimuli." newline ...
"" newline ...
"if nargin < 1 || isempty(stimDir)" newline ...
"    if exist(fullfile(pwd,'stimuli_mp4'), 'dir')" newline ...
"        stimDir = fullfile(pwd, 'stimuli_mp4');" newline ...
"    else" newline ...
"        stimDir = fullfile(pwd, 'stimuli');" newline ...
"    end" newline ...
"end" newline ...
"" newline ...
"if ~exist(stimDir, 'dir')" newline ...
"    error('Stimulus folder not found: %s', stimDir);" newline ...
"end" newline ...
"" newline ...
"files = [dir(fullfile(stimDir, '*.mp4')); dir(fullfile(stimDir, '*.avi'))];" newline ...
"if isempty(files)" newline ...
"    error('No MP4 or AVI files found in %s', stimDir);" newline ...
"end" newline ...
"" newline ...
"filename = strings(numel(files),1);" newline ...
"fullpath = strings(numel(files),1);" newline ...
"signalLabel = strings(numel(files),1);" newline ...
"signalPresent = zeros(numel(files),1);" newline ...
"noise = zeros(numel(files),1);" newline ...
"direction = strings(numel(files),1);" newline ...
"position = zeros(numel(files),1);" newline ...
"" newline ...
"for i = 1:numel(files)" newline ...
"    fname = files(i).name;" newline ...
"    token = regexp(fname, '^([SU])(12|24|48|96|192)([LR])(-?20|-?10|0)\.(avi|mp4)$', 'tokens', 'once');" newline ...
"    if isempty(token)" newline ...
"        error('Filename does not match expected format: %s', fname);" newline ...
"    end" newline ...
"" newline ...
"    filename(i) = string(fname);" newline ...
"    fullpath(i) = string(fullfile(stimDir, fname));" newline ...
"    signalCode = token{1};" newline ...
"    noise(i) = str2double(token{2});" newline ...
"    direction(i) = string(token{3});" newline ...
"    position(i) = str2double(token{4});" newline ...
"" newline ...
"    if strcmp(signalCode, 'U')" newline ...
"        signalLabel(i) = 'walker';" newline ...
"        signalPresent(i) = 1;" newline ...
"    else" newline ...
"        signalLabel(i) = 'scrambled';" newline ...
"        signalPresent(i) = 0;" newline ...
"    end" newline ...
"end" newline ...
"" newline ...
"stimTable = table(filename, fullpath, signalLabel, signalPresent, noise, direction, position);" newline ...
"stimTable = sortrows(stimTable, {'signalLabel','noise','direction','position'});" newline ...
"writetable(stimTable, 'stimuli.csv');" newline ...
