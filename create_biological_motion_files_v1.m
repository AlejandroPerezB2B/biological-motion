"disp(['Stimulus folder: ' stimDir]);" newline ...
"disp(['Number of stimuli found: ' num2str(height(stimTable))]);" newline ...
"" newline ...
"mainRows = ismember(stimTable.noise, [24 48 96 192]);" newline ...
"nMain = sum(mainRows);" newline ...
"if nMain ~= 80" newline ...
"    warning('Expected 80 main-task stimuli with noise 24/48/96/192, but found %d.', nMain);" newline ...
"end" newline ...
"end" newline ...
];
end

