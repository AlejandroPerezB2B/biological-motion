function txt = play_video_code()
txt = [
"function bm_play_video_trial(fig, videoPath)" newline ...
"if ~exist(videoPath, 'file'); error('Video file not found: %s', videoPath); end" newline ...
"try" newline ...
"    vid = VideoReader(videoPath);" newline ...
"catch ME" newline ...
"    error(['Could not read video file:\n%s\n\nOriginal error:\n%s\n\n' ..." newline ...
"        'If this is an AVI file with cvid/Cinepak codec, convert stimuli to MP4 first:\n' ..." newline ...
"        'bm_convert_stimuli_to_mp4\nmake_bm_stimulus_table\nmake_bm_trial_order'], videoPath, ME.message);" newline ...
"end" newline ...
"clf(fig); set(fig,'Color','k');" newline ...
"ax = axes('Parent',fig,'Color','k','Position',[0 0 1 1]); axis(ax,'off');" newline ...
"firstFrame = readFrame(vid);" newline ...
"h = image(ax, firstFrame); axis(ax,'image'); axis(ax,'off'); drawnow;" newline ...
"frameDuration = 1 / vid.FrameRate;" newline ...
"while hasFrame(vid)" newline ...
"    tic;" newline ...
"    frame = readFrame(vid);" newline ...
"    set(h, 'CData', frame);" newline ...
"    drawnow limitrate;" newline ...
"    pause(max(0, frameDuration - toc));" newline ...
"end" newline ...
"end" newline ...
];
end

