function txt = compute_sdt_code()
txt = [
"function summary = bm_compute_sdt(dataFile)" newline ...
"if nargin < 1 || isempty(dataFile)" newline ...
"    [f,p] = uigetfile('*.csv','Select participant data file');" newline ...
"    if isequal(f,0); return; end" newline ...
"    dataFile = fullfile(p,f);" newline ...
"end" newline ...
"T = readtable(dataFile, 'TextType','string');" newline ...
"noiseLevels = unique(T.noise);" newline ...
"rows = table();" newline ...
"overall = computeOne(T, 'overall');" newline ...
"for i = 1:numel(noiseLevels)" newline ...
"    rows = [rows; computeOne(T(T.noise==noiseLevels(i),:), string(noiseLevels(i)))]; %#ok<AGROW>" newline ...
"end" newline ...
"summary = [overall; rows];" newline ...
"[folder,name,~] = fileparts(dataFile);" newline ...
"outFile = fullfile(folder, [name '_SDT_summary.csv']);" newline ...
"writetable(summary, outFile);" newline ...
"disp(summary);" newline ...
"disp(['Saved SDT summary: ' outFile]);" newline ...
"end" newline ...
"" newline ...
"function row = computeOne(T, noiseText)" newline ...
"signalTrials = sum(T.signalPresent == 1);" newline ...
"noiseTrials = sum(T.signalPresent == 0);" newline ...
"hits = sum(T.hit == 1);" newline ...
"falseAlarms = sum(T.falseAlarm == 1);" newline ...
"misses = sum(T.miss == 1);" newline ...
"correctRejections = sum(T.correctRejection == 1);" newline ...
"hitRate = (hits + 0.5) / (signalTrials + 1);" newline ...
"faRate = (falseAlarms + 0.5) / (noiseTrials + 1);" newline ...
"zH = norminv(hitRate);" newline ...
"zFA = norminv(faRate);" newline ...
"dprime = zH - zFA;" newline ...
"criterionC = -0.5 * (zH + zFA);" newline ...
"accuracy = mean(T.correct);" newline ...
"meanRT = mean(T.RT, 'omitnan');" newline ...
"row = table(string(noiseText), signalTrials, noiseTrials, hits, misses, falseAlarms, correctRejections, ..." newline ...
"    hitRate, faRate, dprime, criterionC, accuracy, meanRT, ..." newline ...
"    'VariableNames', {'noise','signalTrials','noiseTrials','hits','misses','falseAlarms', ..." newline ...
"    'correctRejections','hitRate','falseAlarmRate','dprime','criterionC','accuracy','meanRT'});" newline ...
"end" newline ...
];
end

function txt = convert_code()
txt = [
"function bm_convert_stimuli_to_mp4(stimDir, outDir)" newline ...
"% Converts AVI stimuli to MP4 using ffmpeg." newline ...
"% Requires ffmpeg to be installed and available from the system path." newline ...
"" newline ...
"if nargin < 1 || isempty(stimDir); stimDir = fullfile(pwd, 'stimuli'); end" newline ...
"if nargin < 2 || isempty(outDir); outDir = fullfile(pwd, 'stimuli_mp4'); end" newline ...
"if ~exist(stimDir, 'dir'); error('Stimulus folder not found: %s', stimDir); end" newline ...
"if ~exist(outDir, 'dir'); mkdir(outDir); end" newline ...
"" newline ...
"[status, ~] = system('ffmpeg -version');" newline ...
"if status ~= 0" newline ...
"    error(['ffmpeg was not found. Install ffmpeg first, then run this function again.\n' ..." newline ...
"        'On Windows, one option is: winget install Gyan.FFmpeg']);" newline ...
"end" newline ...
"" newline ...
"files = dir(fullfile(stimDir, '*.avi'));" newline ...
"if isempty(files); error('No AVI files found in %s', stimDir); end" newline ...
"" newline ...
"for i = 1:numel(files)" newline ...
"    inFile = fullfile(stimDir, files(i).name);" newline ...
"    [~, base, ~] = fileparts(files(i).name);" newline ...
"    outFile = fullfile(outDir, [base '.mp4']);" newline ...
"    if exist(outFile, 'file')" newline ...
"        fprintf('Already exists: %s\n', outFile);" newline ...
"        continue;" newline ...
"    end" newline ...
"    cmd = sprintf('ffmpeg -y -i ""%s"" -c:v libx264 -pix_fmt yuv420p -an ""%s""', inFile, outFile);" newline ...
"    fprintf('Converting %s\n', files(i).name);" newline ...
"    status = system(cmd);" newline ...
"    if status ~= 0" newline ...
"        error('ffmpeg failed while converting %s', files(i).name);" newline ...
"    end" newline ...
"end" newline ...
"" newline ...
"disp('Conversion finished.');" newline ...
"disp('Now run: make_bm_stimulus_table');" newline ...
"disp('Then run: make_bm_trial_order');" newline ...
"end" newline ...
];
end